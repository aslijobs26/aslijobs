/** Home command-center queue uses the first N items + non-All tabs. */
export function getHomeAttentionSlice() {
  const homeTabs = OPERATIONS_ATTENTION_MOCK.tabs.filter(
    (tab) => tab.id !== "all",
  );
  return {
    attentionTotal: OPERATIONS_ATTENTION_MOCK.total,
    attentionTabs: homeTabs.map((tab) => ({
      id: tab.id as Exclude<(typeof tab)["id"], "all">,
      label: tab.label,
      count: tab.count,
    })),
    attentionItems: OPERATIONS_ATTENTION_MOCK.items,
  };
}
